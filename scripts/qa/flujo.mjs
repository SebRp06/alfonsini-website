import { chromium } from '@playwright/test';
const w = +process.argv[2];
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: w, height: w < 600 ? 812 : 900 } });
await p.goto('http://localhost:3000/producto/aurora', { waitUntil: 'networkidle' });
await p.locator('label', { hasText: /^37/ }).first().click();
await p.getByRole('button', { name: /Empacar talla/ }).click();
await p.waitForTimeout(900); await p.screenshot({ path: `/tmp/empaque-a-${w}.png` });
await p.waitForTimeout(900); await p.screenshot({ path: `/tmp/empaque-b-${w}.png` });
await p.waitForTimeout(1500); await p.screenshot({ path: `/tmp/empaque-c-${w}.png` });
await p.goto('http://localhost:3000/checkout'); await p.waitForTimeout(500);
await p.getByRole('button', { name: /Ir al envío/ }).click(); await p.waitForTimeout(500);
await p.screenshot({ path: `/tmp/checkout-err-${w}.png`, fullPage: true });
await p.getByLabel('Nombres').fill('Ana'); await p.getByLabel('Apellidos').fill('Pérez'); await p.getByLabel('Correo electrónico').fill('a@b.co');
await p.getByLabel('Celular').fill('3105550101'); await p.getByLabel('Cédula').fill('1023456789');
await p.getByRole('button', { name: /Ir al envío/ }).click(); await p.waitForTimeout(400);
await p.getByLabel('Departamento').selectOption('Antioquia'); await p.getByLabel('Ciudad o municipio').fill('Medellín'); await p.getByLabel('Dirección').fill('Calle 10 # 20-30');
await p.getByRole('button', { name: /Ir al pago/ }).click(); await p.waitForTimeout(400);
await p.locator('label', { hasText: 'Transferencia Bre-B' }).click(); await p.getByRole('checkbox').check();
await p.screenshot({ path: `/tmp/checkout-pago-${w}.png`, fullPage: true });
await p.getByRole('button', { name: /Confirmar pedido/ }).click(); await p.waitForTimeout(600);
await p.screenshot({ path: `/tmp/procesando-${w}.png` });
await p.waitForURL(/gracias/); await p.waitForTimeout(3200);
await p.screenshot({ path: `/tmp/gracias-${w}.png`, fullPage: true });
await b.close();
